// Refreshes the bundled catalog snapshot and model id types from the live API.
// Usage: WAIBEE_API_KEY=sk_live_... bun scripts/sync.ts
import { $ } from 'bun'

import { listWaibeeModels } from '../src/catalog.ts'

const models = (await listWaibeeModels({ classes: ['all'] })).toSorted((a, b) =>
  a.id.localeCompare(b.id),
)
const fetchedAt = new Date().toISOString().slice(0, 10)

const union = (ids: string[]) => [...ids.map((id) => `  | '${id}'`), '  | (string & {})'].join('\n')
const idsOf = (modelClass: string) => models.filter((m) => m.class === modelClass).map((m) => m.id)

await Bun.write(
  'src/model-ids.ts',
  `// Generated by scripts/sync.ts from the catalog of ${fetchedAt}. Do not edit.

/** Chat model ids known when the package was built; any other catalog id works too. */
export type WaibeeChatModelId =
${union(idsOf('chat'))}

/** Embedding model ids known when the package was built; any other catalog id works too. */
export type WaibeeEmbeddingModelId =
${union(idsOf('embedding'))}
`,
)

await Bun.write(
  'src/snapshot.ts',
  `// Generated by scripts/sync.ts. Do not edit.
import type { WaibeeModel } from './catalog.ts'

/**
 * The catalog as of \`fetchedAt\`, for offline use: model pickers before a key is set, tests and
 * rough estimates. Prices follow the plan of the key that took the snapshot, so they are
 * approximate; \`listWaibeeModels\` returns the current catalog and the account's own prices.
 */
export const WAIBEE_MODELS_SNAPSHOT: { fetchedAt: string; models: WaibeeModel[] } = ${JSON.stringify(
    { fetchedAt, models },
    null,
    2,
  )}
`,
)

await $`bunx oxfmt src/model-ids.ts`
console.log(`${models.length} models as of ${fetchedAt}`)
